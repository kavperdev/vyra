## Czego uczy nas ten bieg

Nie biegasz 2:06. Ale prawa maratonu są te same na każdym poziomie.

### 1. Maraton zaczyna się po 30. kilometrze

Almgren nie prowadził ani przez metr tam, gdzie prowadzenie nic nie daje. Mantz zaatakował na 35. kilometrze i zapłacił za to na ostatnich siedmiu. Dla amatora oznacza to jedno: **pierwsza połowa ma być „za łatwa”**. Jeśli na 21. kilometrze czujesz, że możesz przyspieszyć, to znaczy, że tempo jest dobre.

### 2. Trasa ustala tempo, nie zegarek

Nowy Jork to mosty (Verrazzano na starcie, Queensboro w połowie, wejście do Bronxu na 20. mili) i długi, łagodny podbieg Piątą Aleją przed Central Parkiem. Na takiej trasie równe tempo na kilometr kosztuje dużo więcej energii niż **równy wysiłek**. Na podbiegach odpuść kilka sekund, na zbiegach ich nie odrabiaj na siłę.

### 3. Debiut nie musi być ostrożny, ale musi być cierpliwy

Almgren przyjechał z szybkością z półmaratonu, ale wykorzystał ją dopiero wtedy, gdy rywale byli zmęczeni. Jeśli przygotowujesz się do pierwszego maratonu, zaplanuj start tak, żeby drugie 21 km było najwyżej minimalnie wolniejsze od pierwszego.

### 4. Siła na końcu to trening, nie charakter

O zwycięstwie zdecydowało to, kto po 2 godzinach biegu wciąż potrafi przyspieszyć. To efekt długich wybiegań z szybszym końcem, treningu progowego i siły biegowej. Taki finisz się buduje, a nie „ma się”.

